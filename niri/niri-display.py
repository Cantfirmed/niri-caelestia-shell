#!/usr/bin/env python3
import glob
import json
import os
import subprocess
import sys
import time

# Allow importing robust KDL parser/serializer from Caelestia Shell scripts directory
_CANDIDATE_SCRIPT_DIRS = [
    os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "scripts")),
    os.path.expanduser("~/.config/niri_caelestia/scripts"),
    os.path.expanduser("~/.config/quickshell/niri-caelestia-shell/scripts"),
]
for _d in _CANDIDATE_SCRIPT_DIRS:
    if os.path.isdir(_d) and _d not in sys.path:
        sys.path.insert(0, _d)

try:
    import update_display as _kdl_engine
except Exception:
    _kdl_engine = None


def ensure_niri_socket():
    """Ensure NIRI_SOCKET is set in os.environ by discovering active niri socket if needed."""
    if "NIRI_SOCKET" in os.environ and os.path.exists(os.environ["NIRI_SOCKET"]):
        return True
    uid = os.getuid()
    runtime_dir = os.environ.get("XDG_RUNTIME_DIR", f"/run/user/{uid}")
    socks = glob.glob(f"{runtime_dir}/niri*.sock") or glob.glob(f"/run/user/{uid}/niri*.sock")
    if socks:
        socks.sort(key=lambda s: os.path.getmtime(s), reverse=True)
        os.environ["NIRI_SOCKET"] = socks[0]
        return True
    return False


def get_drm_connectors():
    """Query sysfs directly for physical DRM connection status."""
    internal = None
    externals = []
    for path in sorted(glob.glob("/sys/class/drm/card*-*/status")):
        parts = os.path.basename(os.path.dirname(path)).split("-", 1)
        if len(parts) > 1:
            conn = parts[1]
            try:
                with open(path) as f:
                    status = f.read().strip()
            except Exception:
                continue
            if status == "connected":
                if conn.startswith(("eDP", "LVDS", "DSI")):
                    internal = conn
                else:
                    externals.append(conn)
    return internal, (externals[0] if externals else None), externals


def is_lid_closed():
    """Check physical lid state."""
    for path in glob.glob("/proc/acpi/button/lid/*/state"):
        try:
            with open(path) as f:
                if "closed" in f.read().lower():
                    return True
        except Exception:
            pass
    return False


def _is_output_disabled_in_kdl(kdl_text, connector):
    if _kdl_engine is not None:
        info = _kdl_engine.extract_output_settings(kdl_text, connector)
        return bool(info.get("off"))
    return (
        f'output "{connector}"' in kdl_text
        and "off" in kdl_text.split(f'output "{connector}"')[1].split("}")[0]
    )


def _write_kdl_updates(output_kdl_path, updates, respect_clamshell=False):
    if _kdl_engine is not None:
        return _kdl_engine.update_multiple_outputs(
            updates,
            config_path=output_kdl_path,
            reload_config=False,
            respect_clamshell=respect_clamshell,
        )
    # Minimal fallback if KDL engine module is unavailable
    lines = ["// Auto-generated by niri-display.py"]
    for spec in updates:
        conn = spec["connector"]
        lines.append(f'output "{conn}" {{')
        if spec.get("off"):
            lines.append("    off")
        else:
            if spec.get("x") is not None and spec.get("y") is not None:
                lines.append(f"    position x={int(spec['x'])} y={int(spec['y'])}")
            if spec.get("scale") is not None:
                lines.append(f"    scale {spec['scale']}")
        lines.append("}")
    kdl_content = "\n".join(lines) + "\n"
    os.makedirs(os.path.dirname(output_kdl_path), exist_ok=True)
    with open(output_kdl_path, "w") as f:
        f.write(kdl_content)
    return kdl_content


def check_sanity():
    """Ensure output.kdl is valid for current physical hardware state BEFORE or during Niri startup."""
    has_internal_hw = any(
        os.path.basename(p).split("-", 1)[-1].startswith(("eDP", "LVDS", "DSI"))
        for p in glob.glob("/sys/class/drm/card*-*")
    )
    if not has_internal_hw:
        return False

    internal_conn, external_conn, all_externals = get_drm_connectors()
    internal_name = internal_conn or "eDP-1"
    output_kdl_path = os.path.expanduser("~/.config/niri/niri/output.kdl")
    lid_closed = is_lid_closed()

    current_kdl = ""
    if os.path.exists(output_kdl_path):
        try:
            with open(output_kdl_path, "r") as f:
                current_kdl = f.read()
        except Exception:
            pass

    updates = []

    if not external_conn:
        internal_disabled = _is_output_disabled_in_kdl(current_kdl, internal_name)
        if internal_disabled or not current_kdl.strip():
            print(
                f"[DisplaySanity] No external display detected, but {internal_name} is disabled. Enabling internal panel...",
                flush=True,
            )
            saved = _kdl_engine.extract_output_settings(current_kdl, internal_name) if _kdl_engine else {}
            spec = {"connector": internal_name, "off": False}
            if "scale" not in saved:
                spec["scale"] = 1.0
            updates.append(spec)
    else:
        if lid_closed:
            internal_disabled = _is_output_disabled_in_kdl(current_kdl, internal_name)
            external_configured = f'output "{external_conn}"' in current_kdl and not _is_output_disabled_in_kdl(
                current_kdl, external_conn
            )
            if not internal_disabled or not external_configured:
                print(
                    f"[DisplaySanity] Clamshell state: Lid closed with {external_conn} connected. Enforcing external-only layout...",
                    flush=True,
                )
                updates.append({"connector": internal_name, "off": True})
                for ext in (all_externals or [external_conn]):
                    saved_ext = _kdl_engine.extract_output_settings(current_kdl, ext) if _kdl_engine else {}
                    ext_spec = {"connector": ext, "off": False}
                    if "scale" not in saved_ext:
                        ext_spec["scale"] = 1.0
                    updates.append(ext_spec)

    if updates:
        _write_kdl_updates(output_kdl_path, updates, respect_clamshell=False)
        if ensure_niri_socket():
            if not external_conn:
                run_cmd(f"niri msg output {internal_name} on")
            elif lid_closed:
                run_cmd(f"niri msg output {internal_name} off")
                for ext in (all_externals or [external_conn]):
                    run_cmd(f"niri msg output {ext} on")
            run_cmd("niri msg action load-config-file")
        return True
    return False


def run_cmd(cmd):
    ensure_niri_socket()
    return subprocess.run(cmd, shell=True, capture_output=True, text=True)


def notify(title, msg, level="info"):
    icon = "monitor"
    if level == "error":
        icon = "error"
    elif level == "warn":
        icon = "warning"

    subprocess.run(
        ["qs", "-c", "niri-caelestia-shell", "ipc", "call", "toaster", level, title, msg, icon],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )


SWITCHING_LOCK = "/tmp/quickshell-display-switching"


def is_wrapper_running():
    """Check if launch-quickshell.sh wrapper is running."""
    res = subprocess.run(["pgrep", "-f", "launch-quickshell.sh"], capture_output=True, text=True)
    return res.returncode == 0


def find_quickshell_pids():
    """Find all quickshell and qs process IDs."""
    result = subprocess.run(["pgrep", "-x", "quickshell|qs"], capture_output=True, text=True)
    if result.returncode != 0:
        return []
    pids = []
    for line in result.stdout.strip().splitlines():
        try:
            pids.append(int(line))
        except ValueError:
            pass
    return list(set(pids))


WAS_LOCKED_BEFORE_KILL = False


def is_session_locked():
    """Check if session is locked via IPC."""
    try:
        res = subprocess.run(
            ["qs", "-c", "niri-caelestia-shell", "ipc", "call", "lock", "isLocked"],
            capture_output=True,
            text=True,
            timeout=1.5,
        )
        if res.returncode == 0 and res.stdout.strip() == "true":
            return True
    except Exception:
        pass
    return False


def kill_quickshell():
    """Kill quickshell and qs processes with SIGKILL to prevent use-after-free crash."""
    global WAS_LOCKED_BEFORE_KILL
    WAS_LOCKED_BEFORE_KILL = is_session_locked()

    pids = find_quickshell_pids()
    if not pids:
        return

    for pid in pids:
        subprocess.run(["kill", "-9", str(pid)], capture_output=True)

    for _ in range(20):
        remaining = find_quickshell_pids()
        if not remaining:
            return
        time.sleep(0.1)

    for pid in find_quickshell_pids():
        subprocess.run(["kill", "-9", str(pid)], capture_output=True)


def restart_quickshell():
    """Restart quickshell after display change."""
    if os.path.exists(SWITCHING_LOCK):
        try:
            os.remove(SWITCHING_LOCK)
        except Exception:
            pass

    if is_wrapper_running():
        for _ in range(30):
            if find_quickshell_pids():
                break
            time.sleep(0.1)
    else:
        wrapper_path = os.path.expanduser("~/.config/niri_caelestia/scripts/launch-quickshell.sh")
        if os.path.exists(wrapper_path):
            subprocess.Popen([wrapper_path], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        else:
            subprocess.Popen(
                ["quickshell", "--path", os.path.expanduser("~/.config/quickshell/niri-caelestia-shell/shell.qml")],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )

    if WAS_LOCKED_BEFORE_KILL:
        for _ in range(25):
            time.sleep(0.2)
            try:
                res = subprocess.run(
                    ["qs", "-c", "niri-caelestia-shell", "ipc", "call", "lock", "lock"],
                    capture_output=True,
                    timeout=1.0,
                )
                if res.returncode == 0:
                    break
            except Exception:
                pass


def _compute_logical_width(conn_name, outputs, current_kdl):
    """Compute logical width accounting for saved/live scale and 90/270 rotation."""
    out_data = outputs.get(conn_name, {})
    logical = out_data.get("logical")
    if logical and logical.get("width"):
        return int(round(logical["width"]))

    saved = _kdl_engine.extract_output_settings(current_kdl, conn_name) if _kdl_engine else {}
    scale = float(saved.get("scale") or (logical.get("scale") if logical else None) or 1.0)
    transform = str(saved.get("transform") or (logical.get("transform") if logical else "normal")).lower()

    raw_w, raw_h = 1920, 1080
    modes = out_data.get("modes", [])
    saved_mode = saved.get("mode")
    matched_mode = False
    if saved_mode and "x" in saved_mode:
        dims = saved_mode.split("@", 1)[0].split("x", 1)
        try:
            raw_w, raw_h = int(dims[0]), int(dims[1])
            matched_mode = True
        except ValueError:
            pass
    if not matched_mode:
        for m in modes:
            if m.get("is_preferred"):
                raw_w, raw_h = m.get("width", 1920), m.get("height", 1080)
                break
        else:
            if modes:
                raw_w, raw_h = modes[0].get("width", 1920), modes[0].get("height", 1080)

    rotated = transform in ("90", "_90", "270", "_270", "flipped-90", "flipped-270", "flipped90", "flipped270")
    effective_px = raw_h if rotated else raw_w
    return max(1, int(round(effective_px / max(0.1, scale))))


def main():
    if len(sys.argv) < 2:
        print("Usage: niri-display.py [internal|external|extend-left|extend-right|restore-extended|duplicate|--sanity-check]")
        sys.exit(1)

    if sys.argv[1] in ("--sanity-check", "-s", "sanity"):
        check_sanity()
        sys.exit(0)

    mode = sys.argv[1]
    turning_off_display = mode in ("internal", "external")

    res = run_cmd("niri msg --json outputs")
    if res.returncode != 0:
        if turning_off_display:
            restart_quickshell()
        notify("Display Switcher", "Error: Niri is not running or IPC failed", "error")
        sys.exit(1)

    try:
        outputs = json.loads(res.stdout)
    except Exception as e:
        if turning_off_display:
            restart_quickshell()
        notify("Display Switcher", f"Failed to parse Niri outputs: {e}", "error")
        sys.exit(1)

    internal = None
    externals = []
    for name in outputs:
        if name.startswith(("eDP", "LVDS", "DSI")):
            internal = name
        else:
            externals.append(name)

    if not internal:
        internal = list(outputs.keys())[0] if outputs else "eDP-1"

    if not externals:
        _, drm_ext, drm_exts = get_drm_connectors()
        if drm_exts:
            externals = drm_exts
        elif drm_ext:
            externals = [drm_ext]

    external = externals[0] if externals else None

    if not external:
        if mode in ("external", "extend", "extend-left", "extend-right", "restore-extended", "duplicate"):
            notify("Display Switcher", "No external display detected.", "warn")
            mode = "internal"

    run_cmd("pkill wl-mirror")

    output_kdl_path = os.path.expanduser("~/.config/niri/niri/output.kdl")
    current_content = ""
    if os.path.exists(output_kdl_path):
        try:
            with open(output_kdl_path, "r") as f:
                current_content = f.read()
        except Exception:
            pass

    internal_width = _compute_logical_width(internal, outputs, current_content)
    external_width = _compute_logical_width(external, outputs, current_content) if external else 1920

    saved_int = _kdl_engine.extract_output_settings(current_content, internal) if _kdl_engine else {}
    saved_ext = (_kdl_engine.extract_output_settings(current_content, external) if (_kdl_engine and external) else {})

    updates = []
    if mode == "internal":
        int_spec = {"connector": internal, "off": False}
        if "scale" not in saved_int:
            int_spec["scale"] = 1.0
        updates.append(int_spec)
        for ext in externals:
            updates.append({"connector": ext, "off": True})

    elif mode == "external":
        updates.append({"connector": internal, "off": True})
        for ext in externals:
            saved_e = _kdl_engine.extract_output_settings(current_content, ext) if _kdl_engine else {}
            ext_spec = {"connector": ext, "off": False}
            if "scale" not in saved_e:
                ext_spec["scale"] = 1.0
            updates.append(ext_spec)

    elif mode == "restore-extended":
        # Re-enable internal + all externals while preserving saved multi-monitor layout if non-overlapping
        has_distinct_pos = (
            "x" in saved_int
            and "x" in saved_ext
            and (saved_int.get("x") != saved_ext.get("x") or saved_int.get("y") != saved_ext.get("y"))
        )
        int_spec = {"connector": internal, "off": False}
        if "scale" not in saved_int:
            int_spec["scale"] = 1.0
        if not has_distinct_pos:
            int_spec["x"] = 0
            int_spec["y"] = 0
        updates.append(int_spec)

        cursor_x = internal_width
        for idx, ext in enumerate(externals):
            saved_e = _kdl_engine.extract_output_settings(current_content, ext) if _kdl_engine else {}
            ext_spec = {"connector": ext, "off": False}
            if "scale" not in saved_e:
                ext_spec["scale"] = 1.0
            if not has_distinct_pos and idx == 0:
                ext_spec["x"] = cursor_x
                ext_spec["y"] = 0
            updates.append(ext_spec)
            cursor_x += _compute_logical_width(ext, outputs, current_content)

    elif mode == "extend-left":
        int_spec = {"connector": internal, "off": False, "x": external_width, "y": 0}
        if "scale" not in saved_int:
            int_spec["scale"] = 1.0
        updates.append(int_spec)
        if external:
            ext_spec = {"connector": external, "off": False, "x": 0, "y": 0}
            if "scale" not in saved_ext:
                ext_spec["scale"] = 1.0
            updates.append(ext_spec)

    elif mode in ("extend-right", "extend", "duplicate"):
        int_spec = {"connector": internal, "off": False, "x": 0, "y": 0}
        if "scale" not in saved_int:
            int_spec["scale"] = 1.0
        updates.append(int_spec)
        cursor_x = internal_width
        for ext in externals:
            saved_e = _kdl_engine.extract_output_settings(current_content, ext) if _kdl_engine else {}
            ext_spec = {"connector": ext, "off": False, "x": cursor_x, "y": 0}
            if "scale" not in saved_e:
                ext_spec["scale"] = 1.0
            updates.append(ext_spec)
            cursor_x += _compute_logical_width(ext, outputs, current_content)

        if mode == "duplicate":
            check_mirror = run_cmd("which wl-mirror")
            if check_mirror.returncode == 0:
                subprocess.Popen(["wl-mirror", internal], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            else:
                notify(
                    "Mirroring Failed",
                    "wl-mirror is not installed. Mirroring window could not be opened.",
                    "error",
                )

    new_content = (
        _kdl_engine.update_kdl_content(current_content or "// --- Output Configuration ---\n", updates)
        if _kdl_engine is not None
        else None
    )

    if new_content is not None and current_content.strip() == new_content.strip():
        int_active = bool(outputs.get(internal, {}).get("logical"))
        ext_active = bool(external and outputs.get(external, {}).get("logical"))
        if mode == "external" and not int_active and ext_active:
            return
        if mode == "internal" and int_active and not ext_active:
            return
        if mode in ("extend-left", "extend-right", "extend", "restore-extended", "duplicate") and int_active and ext_active:
            return

    try:
        _write_kdl_updates(output_kdl_path, updates, respect_clamshell=(mode == "external"))
    except Exception as e:
        if turning_off_display:
            restart_quickshell()
        notify("Display Switcher", f"Failed to write config: {e}", "error")
        sys.exit(1)

    try:
        open(SWITCHING_LOCK, "w").close()
    except Exception:
        pass

    try:
        kill_quickshell()

        if mode == "internal":
            run_cmd(f"niri msg output {internal} on")
            for ext in externals:
                run_cmd(f"niri msg output {ext} off")
        elif mode == "external":
            run_cmd(f"niri msg output {internal} off")
            for ext in externals:
                run_cmd(f"niri msg output {ext} on")
        elif mode in ("extend-left", "extend-right", "extend", "restore-extended", "duplicate"):
            run_cmd(f"niri msg output {internal} on")
            for ext in externals:
                run_cmd(f"niri msg output {ext} on")

        res_reload = run_cmd("niri msg action load-config-file")
        if res_reload.returncode != 0:
            notify("Display Switcher", "Failed to reload Niri config", "error")
            sys.exit(1)

        time.sleep(0.5)
    finally:
        restart_quickshell()

    mode_title = {
        "internal": "Laptop Screen Only",
        "external": "External Screen Only",
        "extend": "Extend Desktop",
        "extend-left": "Extend Left",
        "extend-right": "Extend Right",
        "restore-extended": "Extended Desktop",
        "duplicate": "Duplicate/Mirror",
    }.get(mode, mode)

    time.sleep(1.0)
    notify("Display Switcher", f"Layout changed to {mode_title}", "success")


if __name__ == "__main__":
    main()
